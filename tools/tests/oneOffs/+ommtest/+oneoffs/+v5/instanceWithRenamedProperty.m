function [instance, propertyName, schemaName] = instanceWithRenamedProperty()
% instanceWithRenamedProperty - Create a v5 GridImageStack, whose zStepSize is "z-stepSize" in the schema.

    propertyName = "zStepSize";
    schemaName = "z-stepSize";

    instance = openminds.core.GridImageStack( ...
        "name", "stack", ...
        "dimension", int64([512, 512]), ...
        "pixelSize", [ ...
            openminds.core.QuantitativeValue("value", 0.5), ...
            openminds.core.QuantitativeValue("value", 0.6)], ...
        "zStepSize", openminds.core.QuantitativeValue("value", 2.5));
end
